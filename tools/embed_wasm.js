'use strict';
// Embeds a .wasm file as base64 in a plain script so index.html works from file:// (no fetch / local server needed).
//   node tools/embed_wasm.js build/game.wasm js/wasm_blob.js
const fs = require('fs');
const [, , src, dst] = process.argv;
const b64 = fs.readFileSync(src).toString('base64');
fs.writeFileSync(dst, '/* GENERATED by tools/embed_wasm.js from c/game.c — do not edit. */\nconst GAME_WASM_BASE64 = "' + b64 + '";\n');
console.log('wrote', dst, '(' + fs.statSync(src).size + ' bytes of wasm)');
