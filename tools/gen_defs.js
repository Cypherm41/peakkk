'use strict';
// Generates c/defs.h from js/defs.js so the C core and the UI share one set of numbers.
//   node tools/gen_defs.js
const fs = require('fs');
const path = require('path');
const D = require('../js/defs.js');

const resIdx = (r) => D.RES_LIST.indexOf(r);
const cost4 = (c) => '{' + D.RES_LIST.map((r) => (c && c[r]) || 0).join(',') + '}';
const f = (n) => (Number.isInteger(n) ? n + '.0' : String(n));

let o = '/* GENERATED by tools/gen_defs.js from js/defs.js — do not edit by hand. */\n#ifndef DEFS_H\n#define DEFS_H\n\n';
o += `#define MAP_W ${D.MAP_W}\n#define MAP_H ${D.MAP_H}\n#define MAX_POP ${D.MAX_POP}\n`;
o += `#define FARM_RATE ${f(D.FARM_RATE)}\n#define FARM_SLOTS ${D.FARM_SLOTS}\n`;
o += `#define NUM_UNIT ${D.UNIT_KEYS.length}\n#define NUM_BLD ${D.BUILDING_KEYS.length}\n#define NUM_NODE ${D.NODE_KEYS.length}\n#define NUM_TECH ${D.TECH_KEYS.length}\n#define NUM_CLS ${D.CLASSES.length}\n\n`;
D.UNIT_KEYS.forEach((k, i) => { o += `#define U_${k.toUpperCase()} ${i}\n`; });
D.BUILDING_KEYS.forEach((k, i) => { o += `#define B_${k.toUpperCase()} ${i}\n`; });
D.NODE_KEYS.forEach((k, i) => { o += `#define N_${k.toUpperCase()} ${i}\n`; });
D.TECH_KEYS.forEach((k, i) => { o += `#define TECH_${k.toUpperCase()} ${i}\n`; });
D.CLASSES.forEach((k, i) => { o += `#define CLS_${k.toUpperCase()} ${i}\n`; });
o += '\n';

o += `typedef struct {
  double hp, speed, atk; int atkType; double range, cd; double bonus[NUM_CLS]; int armor[3];
  int cost[4]; double time; int pop; double sight, carry; int water, soldier, cls, big;
} UnitDef;
typedef struct {
  int w, h; double hp; int cost[4]; double time; int pop, drop, farm, shore;
  double atk; int atkType; double range, cd; int trains[2]; int research[2];
} BldDef;
typedef struct { int res; double amt, rate; } NodeDef;
typedef struct { int max; int base[2], step[2]; double tbase, tstep; } TechDef;  /* [food, gold] */
typedef struct { double gather; int maxB, wave, grow; double pace; int bonus; double think; } DiffDef;

`;

o += 'static const UnitDef UDEF[NUM_UNIT] = {\n';
for (const k of D.UNIT_KEYS) {
  const u = D.UNIT_DEFS[k];
  const bonus = D.CLASSES.map((c) => f((u.bonus && u.bonus[c]) || 0)).join(',');
  o += `  /* ${k} */ { ${f(u.hp)}, ${f(u.speed)}, ${f(u.atk)}, ${D.ATK_TYPES.indexOf(u.atkType)}, ${f(u.range)}, ${f(u.cd)}, {${bonus}}, {${u.armor.melee},${u.armor.pierce},${u.armor.siege}}, ` +
       `${cost4(u.cost)}, ${f(u.time)}, ${u.pop}, ${f(u.sight)}, ${f(u.carry || 0)}, ${u.domain === 'water' ? 1 : 0}, ${u.role === 'soldier' ? 1 : 0}, ${D.CLASSES.indexOf(u.cls)}, ${u.big ? 1 : 0} },\n`;
}
o += '};\n\nstatic const BldDef BDEF[NUM_BLD] = {\n';
for (const k of D.BUILDING_KEYS) {
  const b = D.BUILDING_DEFS[k];
  const tr = (b.trains || []).map((t) => D.UNIT_KEYS.indexOf(t)); while (tr.length < 2) tr.push(-1);
  const rs = (b.research || []).map((t) => D.TECH_KEYS.indexOf(t)); while (rs.length < 2) rs.push(-1);
  o += `  /* ${k} */ { ${b.w}, ${b.h}, ${f(b.hp)}, ${cost4(b.cost)}, ${f(b.time)}, ${b.pop || 0}, ${b.drop ? 1 : 0}, ${b.farm ? 1 : 0}, ${b.shore ? 1 : 0}, ` +
       `${f(b.atk || 0)}, ${b.atkType ? D.ATK_TYPES.indexOf(b.atkType) : 1}, ${f(b.range || 0)}, ${f(b.cd || 0)}, {${tr.join(',')}}, {${rs.join(',')}} },\n`;
}
o += '};\n\nstatic const NodeDef NDEF[NUM_NODE] = {\n';
for (const k of D.NODE_KEYS) { const n = D.NODE_DEFS[k]; o += `  /* ${k} */ { ${resIdx(n.res)}, ${f(n.amt)}, ${f(n.rate)} },\n`; }
o += '};\n\nstatic const TechDef TDEF[NUM_TECH] = {\n';
for (const k of D.TECH_KEYS) {
  const t = D.TECHS[k];
  o += `  /* ${k} */ { ${t.max}, {${t.base.food},${t.base.gold}}, {${t.step.food},${t.step.gold}}, ${f(t.tbase)}, ${f(t.tstep)} },\n`;
}
o += '};\n\nstatic const DiffDef DIFFD[3] = {\n';
for (const k of D.DIFF_KEYS) {
  const d = D.DIFFS[k];
  o += `  /* ${k} */ { ${f(d.gather)}, ${d.maxB}, ${d.wave}, ${d.grow}, ${f(d.pace)}, ${d.bonus}, ${f(d.think)} },\n`;
}
o += '};\n\n#endif\n';

const out = path.join(__dirname, '..', 'c', 'defs.h');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, o);
console.log('wrote', out);
