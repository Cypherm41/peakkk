'use strict';
// Generates sdl/gamedata.h from js/defs.js: the display data the SDL2 front end needs and c/defs.h doesn't carry
// (names, descriptions, building draw heights, team colours). Keeps js/defs.js the single source of truth.
//   node tools/gen_sdl_data.js
const fs = require('fs');
const path = require('path');
const D = require('../js/defs.js');

// The bitmap font is ASCII only, so fold the few typographic characters a description might contain.
const ascii = (s) => String(s).replace(/[–—]/g, '-').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/·/g, '-');
const q = (s) => {
  const a = ascii(s);
  if (/[^\x20-\x7e]/.test(a)) throw new Error('non-ASCII text in defs.js: ' + s);
  return '"' + a.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
};
const hex = (c) => '0x' + c.replace('#', '').toLowerCase();

let o = '/* GENERATED by tools/gen_sdl_data.js from js/defs.js — do not edit by hand. */\n#ifndef GAMEDATA_H\n#define GAMEDATA_H\n\n';
const arr = (name, keys, get) => {
  o += `static const char *${name}[${keys.length}] = {\n`;
  for (const k of keys) o += `  /* ${k} */ ${q(get(k))},\n`;
  o += '};\n';
};
arr('UNIT_NAME', D.UNIT_KEYS, (k) => D.UNIT_DEFS[k].name);
arr('UNIT_DESC', D.UNIT_KEYS, (k) => D.UNIT_DEFS[k].desc);
arr('BLD_NAME', D.BUILDING_KEYS, (k) => D.BUILDING_DEFS[k].name);
arr('BLD_DESC', D.BUILDING_KEYS, (k) => D.BUILDING_DEFS[k].desc);
arr('TECH_NAME', D.TECH_KEYS, (k) => D.TECHS[k].name);
arr('TECH_DESC', D.TECH_KEYS, (k) => D.TECHS[k].desc);
arr('NODE_NAME', D.NODE_KEYS, (k) => D.NODE_DEFS[k].name);
arr('MAP_NAME', D.MAP_KEYS, (k) => D.MAPS[k].name);
arr('MAP_DESC', D.MAP_KEYS, (k) => D.MAPS[k].desc);
o += `#define MAP_COUNT ${D.MAP_KEYS.length}\n`;

o += `\nstatic const float BLD_HEIGHT[${D.BUILDING_KEYS.length}] = { ${D.BUILDING_KEYS.map((k) => (D.BUILDING_DEFS[k].height || 20) + '.0f').join(', ')} };\n`;
o += `\nstatic const char *TEAM_NAME[${D.TEAMS.length}] = { ${D.TEAMS.map((t) => q(t.name)).join(', ')} };\n`;
o += `static const unsigned TEAM_COLOR[${D.TEAMS.length}] = { ${D.TEAMS.map((t) => hex(t.color)).join(', ')} };\n`;
o += `static const unsigned TEAM_DARK[${D.TEAMS.length}] = { ${D.TEAMS.map((t) => hex(t.dark)).join(', ')} };\n`;
o += `static const unsigned TEAM_LIGHT[${D.TEAMS.length}] = { ${D.TEAMS.map((t) => hex(t.light)).join(', ')} };\n`;
o += '\n#endif\n';

const out = path.join(__dirname, '..', 'sdl', 'gamedata.h');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, o);
console.log('wrote', out);
